import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const skillPath = resolve(root, 'apps/agent-runner/skills/workmesh-workbench/SKILL.md')
const manifestPath = resolve(root, 'apps/agent-runner/src/workbench-skill-manifest.ts')
// The pin is over the canonical LF bytes. Reading and normalizing keeps the
// digest identical on a Windows checkout, where the worktree may hold CRLF until
// .gitattributes forces the file to LF.
const normalizeLineEndings = value => value.replace(/\r\n/g, '\n')
const content = normalizeLineEndings(await readFile(skillPath, 'utf8'))
const sha256 = `sha256:${createHash('sha256').update(content).digest('hex')}`
const manifest = `// Generated by scripts/generate-runner-skill-manifest.mjs.\nexport const workbenchSkillManifest = Object.freeze({\n  name: 'workmesh-workbench' as const,\n  version: '0.1.0' as const,\n  sha256: '${sha256}',\n})\n`

if (process.argv.includes('--check')) {
  // Compare the pinned digest rather than the whole generated file so a checkout
  // with different line endings is not reported as a stale pin.
  const pinned = /sha256: '([^']+)'/.exec(await readFile(manifestPath, 'utf8'))
  if (!pinned || pinned[1] !== sha256)
    throw new Error('Pi Runner Skill manifest is stale')
  process.stdout.write(`${sha256} verified\n`)
} else {
  await writeFile(manifestPath, manifest)
  process.stdout.write(`${sha256} pinned\n`)
}
