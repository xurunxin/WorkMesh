// Generates the public, signed Workbench Skill artifact for release.
//
// The runner embeds the SKILL.md bytes directly (see workbench-skill-manifest.ts),
// which pins what the Runner executes. The public artifact is the release copy of the
// same bytes: published under apps/web/public/skills, hashed, and signed with the
// WorkMesh Skill ed25519 key, so a Human or a deployment can verify that the
// published instructions are exactly the ones the Runner enforces.
//
// Signing requires WORKMESH_SKILL_SIGNING_PRIVATE_KEY_FILE (the same key used for
// the workmesh Skill). Verification needs only the committed public key.
import { createHash, createPublicKey, sign, verify } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const check = process.argv.includes('--check')
const skillPath = resolve(root, 'apps/agent-runner/skills/workmesh-workbench/SKILL.md')
const publicKeyPath = resolve(root, 'skills/workmesh/public-key.pem')
const version = '1.0.0'
const artifactPath = resolve(root, `apps/web/public/skills/workmesh-workbench-${version}.md`)
const manifestPath = resolve(root, 'packages/contracts/src/workbench-skill-release-manifest.ts')

// The pin and the artifact are over the canonical LF bytes, so a Windows checkout
// with CRLF line endings cannot change the digest.
const normalizeLineEndings = value => value.replace(/\r\n/g, '\n')
const artifact = `${normalizeLineEndings(await readFile(skillPath, 'utf8')).trim()}\n`
const digest = `sha256:${createHash('sha256').update(artifact).digest('hex')}`

if (check) {
  const [actualArtifact, manifestSource, publicKey] = await Promise.all([
    readFile(artifactPath), readFile(manifestPath, 'utf8'), readFile(publicKeyPath, 'utf8'),
  ])
  const expectedArtifact = Buffer.from(artifact, 'utf8')
  if (!actualArtifact.equals(expectedArtifact))
    throw new Error('Generated Workbench Skill artifact bytes are stale or not canonical LF UTF-8')
  const actualDigest = `sha256:${createHash('sha256').update(actualArtifact).digest('hex')}`
  const manifest = /sha256: '([^']+)',\s+signature: 'ed25519:([^']+)',/s.exec(manifestSource)
  if (!manifest || manifest[1] !== digest || manifest[1] !== actualDigest)
    throw new Error('Generated Workbench Skill release manifest is stale')
  if (!verify(null, actualArtifact, publicKey, Buffer.from(manifest[2], 'base64')))
    throw new Error('Workbench Skill signature is invalid for the exact published bytes')
  process.stdout.write(`${actualDigest} verified\n`)
  process.exit(0)
}

const privateKeyPath = process.env.WORKMESH_SKILL_SIGNING_PRIVATE_KEY_FILE
if (!privateKeyPath) throw new Error('WORKMESH_SKILL_SIGNING_PRIVATE_KEY_FILE is required to generate a signed Workbench Skill artifact')
const privateKey = await readFile(privateKeyPath, 'utf8')
const publicKey = createPublicKey(privateKey).export({ type: 'spki', format: 'pem' })
const signature = sign(null, Buffer.from(artifact), privateKey).toString('base64')
await writeFile(artifactPath, artifact)
await writeFile(publicKeyPath, publicKey)
await writeFile(manifestPath,
  `// Generated by scripts/generate-workbench-skill-artifact.mjs.\n` +
  `export const workbenchSkillReleaseManifest = Object.freeze({\n` +
  `  name: 'workmesh-workbench' as const,\n` +
  `  version: '${version}',\n` +
  `  sha256: '${digest}',\n` +
  `  signature: 'ed25519:${signature}',\n` +
  `})\n`)
process.stdout.write(`${digest} signed\n`)
