import { createHash, createPublicKey, sign, verify } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const check = process.argv.includes('--check')
const skillPath = resolve(root, 'skills/workmesh/SKILL.md')
const protocolPath = resolve(root, 'skills/workmesh/references/protocol.md')
const clientsPath = resolve(root, 'skills/workmesh/references/clients.md')
const artifactPath = resolve(root, 'apps/web/public/skills/workmesh-1.1.0.md')
const manifestPath = resolve(root, 'packages/contracts/src/workmesh-skill-manifest.ts')
const publicKeyPath = resolve(root, 'skills/workmesh/public-key.pem')

const normalizeLineEndings = value => value.replace(/\r\n/g, '\n')
const sections = (await Promise.all([skillPath, protocolPath, clientsPath].map(path => readFile(path, 'utf8')))).map(normalizeLineEndings)
const artifact = `${sections[0].trim()}\n\n---\n\n${sections[1].trim()}\n\n---\n\n${sections[2].trim()}\n`
const digest = `sha256:${createHash('sha256').update(artifact).digest('hex')}`

if (check) {
  const [actualArtifact, manifestSource, publicKey] = await Promise.all([
    readFile(artifactPath), readFile(manifestPath, 'utf8'), readFile(publicKeyPath, 'utf8'),
  ])
  const expectedArtifact = Buffer.from(artifact, 'utf8')
  if (!actualArtifact.equals(expectedArtifact))
    throw new Error('Generated WorkMesh Skill artifact bytes are stale or not canonical LF UTF-8')
  const actualDigest = `sha256:${createHash('sha256').update(actualArtifact).digest('hex')}`
  const manifest = /sha256: '([^']+)',\s+signature: 'ed25519:([^']+)'/s.exec(manifestSource)
  if (!manifest || manifest[1] !== digest || manifest[1] !== actualDigest)
    throw new Error('Generated WorkMesh Skill manifest is stale')
  if (!verify(null, actualArtifact, publicKey, Buffer.from(manifest[2], 'base64')))
    throw new Error('WorkMesh Skill signature is invalid for the exact published bytes')
  process.stdout.write(`${actualDigest} verified\n`)
  process.exit(0)
}

const privateKeyPath = process.env.WORKMESH_SKILL_SIGNING_PRIVATE_KEY_FILE
if (!privateKeyPath) throw new Error('WORKMESH_SKILL_SIGNING_PRIVATE_KEY_FILE is required to generate a signed Skill artifact')
const privateKey = await readFile(privateKeyPath, 'utf8')
const publicKey = createPublicKey(privateKey).export({ type: 'spki', format: 'pem' })
const signature = sign(null, Buffer.from(artifact), privateKey).toString('base64')
await writeFile(artifactPath, artifact)
await writeFile(publicKeyPath, publicKey)
await writeFile(manifestPath, `// Generated by scripts/generate-workmesh-skill-artifact.mjs.\nexport const workmeshSkillManifest = Object.freeze({\n  name: 'workmesh' as const,\n  version: '1.1.0',\n  sha256: '${digest}',\n  signature: 'ed25519:${signature}',\n})\n`)
process.stdout.write(`${digest} signed\n`)
